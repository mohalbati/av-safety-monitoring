"""Workflow diagram for the technical report (results/fig0_workflow.png)."""
import os
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch
OUT = os.path.join(os.path.dirname(__file__), "..", "results")
fig, ax = plt.subplots(figsize=(11, 4.4)); ax.set_xlim(0, 11); ax.set_ylim(0, 4.4); ax.axis("off")
def box(x, y, w, h, title, body, fc, ec):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.02,rounding_size=0.08", fc=fc, ec=ec, lw=1.4))
    ax.text(x + 0.12, y + h - 0.16, title, fontsize=9.5, weight="bold", va="top", color="#14213D")
    ax.text(x + 0.12, y + h - 0.48, body, fontsize=8, va="top", color="#36404E", linespacing=1.35)
def arrow(x1, y1, x2, y2):
    ax.annotate("", (x2, y2), (x1, y1), arrowprops=dict(arrowstyle="-|>", color="#5B6472", lw=1.3))
box(0.1, 1.5, 2.0, 1.5, "1. Inputs", "NHTSA SGO crash reports\n(Repo 1 rates, 271.3M mi)\nFleet exposure 2.9M mi/wk\nAssumed leading indicator", "#EEF3FB", "#2A78D6")
box(2.6, 2.95, 2.5, 1.3, "2. Detectability", "Exact Poisson power\nMiles and weeks to detect\nStaged rollout, two-sample", "#FFFFFF", "#2A78D6")
box(2.6, 1.5, 2.5, 1.3, "3. Test coverage", "Zero-failure demonstration\nAllowed failures, Bayesian\nOperating characteristic", "#FFFFFF", "#2A78D6")
box(2.6, 0.05, 2.5, 1.3, "4. Field monitoring", "Poisson CUSUM, calibrated h\nMarkov-chain verification\nFalse-alarm budget", "#FFFFFF", "#2A78D6")
box(5.6, 1.5, 2.3, 1.5, "5. Risk register", "ISO 31000 lifecycle\nGamma / Beta posteriors\nRanking probabilities\nData gaps flagged", "#FFFFFF", "#7A4FB0")
box(8.4, 1.5, 2.5, 1.5, "6. Release health report", "Generated by one script\nBottom line first\nStatus, top risks, gaps,\nactions", "#FFF4EC", "#EB6834")
for y in (3.6, 2.15, 0.7):
    arrow(2.1, 2.25, 2.6, y)
    arrow(5.1, y, 5.6, 2.25)
arrow(7.9, 2.25, 8.4, 2.25)
ax.text(5.5, 0.15, "Simulated release history (104 weeks, regression at week 60) exercises steps 4–6", fontsize=8, color="#5B6472")
fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig0_workflow.png"), dpi=170)
